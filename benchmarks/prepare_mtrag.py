"""Download pinned MTRAG conversations and make a bounded, public multi-turn fixture.

All passages supplied by the annotators are preserved. The corpus is a reduced
passage pool, not the official full-domain corpus. Original reviewed answers and
latest passage relevance annotations are retained, never generated by ERAG.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import random
from collections import defaultdict
from pathlib import Path

from erag.resources import DEFAULT_MANIFEST, download, downloaded_path, read_manifest

RESOURCE = next(r for r in read_manifest(DEFAULT_MANIFEST) if r["name"] == "mtrag")
REVISION, URL, SHA256 = RESOURCE["revision"], RESOURCE["url"], RESOURCE["sha256"]


def latest_relevant(context):
    annotations = context.get("feedback", {}).get("relevant", {}).values()
    return max(annotations, key=lambda x: x.get("timestamp", 0), default={}).get("value") == "yes"


def prepare(conversations, seed=47):
    groups = defaultdict(list)
    pool = {}
    for index, conversation in enumerate(conversations):
        groups[conversation["retriever"]["collection"]["name"]].append(index)
        for message in conversation["messages"]:
            for context in message.get("contexts", []):
                identity = context["document_id"]
                if identity in pool and pool[identity]["text"] != context["text"]:
                    raise ValueError(f"Conflicting passage: {identity}")
                pool[identity] = {"id": identity, "text": context["text"], "title": context.get("title", "")}
    rng = random.Random(seed)
    selected = [i for domain in sorted(groups) for i in rng.sample(groups[domain], 2)]
    sessions, included = [], set()
    for n, index in enumerate(selected):
        conversation = conversations[index]
        history, turns = [], []
        messages = conversation["messages"]
        for offset in range(0, min(len(messages), 12), 2):
            question, answer = messages[offset : offset + 2]
            assert question["speaker"] == "user" and answer["speaker"] == "agent"
            contexts = answer.get("contexts", [])
            included.update(c["document_id"] for c in contexts)
            turns.append(
                {
                    "query": question["text"],
                    "reference_answer": answer["text"],
                    "history": list(history),
                    "relevant": sorted(c["document_id"] for c in contexts if latest_relevant(c)),
                    "labels": question.get("enrichments", {}),
                }
            )
            history.extend(
                [
                    {"role": "user", "content": question["text"]},
                    {"role": "assistant", "content": answer["text"]},
                ]
            )
        sessions.append(
            {
                "id": f"mtrag-{index}",
                "domain": conversation["domain"],
                "split": "development" if n in {0, 2} else "test",
                "turns": turns,
            }
        )
    extra = set(rng.sample(sorted(pool.keys() - included), min(192, len(pool.keys() - included))))
    return {
        "source": {"url": URL, "revision": REVISION, "sha256": SHA256},
        "seed": seed,
        "limitation": "Reduced annotated-passage corpus. Teacher-forced original history; not autonomous rollout or full MTRAG score.",
        "sessions": sessions,
        "documents": [pool[i] for i in sorted(included | extra)],
        "selection": {
            "conversation_indices": selected,
            "context_documents": len(included),
            "distractors": len(extra),
        },
    }


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--resources-root", type=Path, default=Path("resources"))
    p.add_argument("--output", type=Path, required=True)
    args = p.parse_args()
    download([RESOURCE], args.resources_root)
    path = Path(downloaded_path(args.resources_root, "mtrag")) / RESOURCE["filename"]
    if hashlib.sha256(path.read_bytes()).hexdigest() != SHA256:
        raise ValueError("Dataset checksum mismatch")
    fixture = prepare(json.loads(path.read_text()))
    args.output.mkdir(parents=True, exist_ok=False)
    (args.output / "fixture.json").write_text(json.dumps(fixture, ensure_ascii=False, indent=2))
    print(
        json.dumps(
            {
                "conversations": len(fixture["sessions"]),
                "turns": sum(len(s["turns"]) for s in fixture["sessions"]),
                "documents": len(fixture["documents"]),
                **fixture["selection"],
            }
        )
    )


if __name__ == "__main__":
    main()
